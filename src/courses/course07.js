// ============================================================
// GENERATE MODULAR TERRAIN FEATURES
// ============================================================

// Fixed feature data keeps the geography
// deterministic across game sessions and previews.

const hills = [
  ...LARGE_HILLS,
  ...SMALL_HILLS,
].map(([x, z, radius, height]) =>
  terrainBrick.hill({
    position: [x, z],
    radius,
    height,
    blend: "add",
  })
);

const valleys = [
  ...LARGE_VALLEYS,
  ...SMALL_VALLEYS,
].map(([x, z, radius, depth]) =>
  terrainBrick.valley({
    position: [x, z],
    radius,
    depth,
    blend: "add",
  })
);

// ============================================================
// COURSE DEFINITION
// ============================================================

const course07 = createLayoutCourse({
  id: "course-07",
  number: 7,
  name: "Rolling Fields",
  environment: "garden",
  par: 3,

  // ----------------------------------------------------------
  // START AND HOLE
  // ----------------------------------------------------------

  ballStart: [0, 0.25, 9],

  hole: {
    position: [-0.1, 0, -8.4],
    radius: 0.43,
  },

  // ----------------------------------------------------------
  // WIDE FIELD GEOMETRY
  // ----------------------------------------------------------

  shape: {
    type: "rounded",
    points: FIELD_POINTS,

    tolerance: 0.025,
    maxSegmentLength: 0.6,

    color: GRASS_COLOR,

    wall: {
      color: WALL_COLOR,
      height: 0.55,
      thickness: 0.25,
      friction: 0.8,
      restitution: 0.3,
    },
  },

  // ----------------------------------------------------------
  // TERRAIN SETTINGS
  // ----------------------------------------------------------

  terrain: {
    width: 34,
    length: 32,
    resolution: 128,

    baseHeight: 0,
    defaultSurface: "grass",
    color: GRASS_COLOR,
  },

  // ----------------------------------------------------------
  // TERRAIN FEATURES
  // ----------------------------------------------------------

  geography: {
    features: [
      ...hills,
      ...valleys,
    ],
  },

  // ----------------------------------------------------------
  // VALIDATION
  // ----------------------------------------------------------

  validate: import.meta.env.DEV,
});

